/** ステージ一覧を作る。PAR は最短手数から自動計算。 */
export function buildStages(){
  return DEFS.map((def, i) => {
    const challenge = fromGrid(def.grid, def.dir, 1);
    const optimal = optimalCommands(challenge);
    if (optimal === null) throw new Error(`ステージ ${def.id} はゴールに到達できません`);
    challenge.par = optimal + 1;
    return { ...def, no: i + 1, challenge, optimal };
  });
}

export const STAGE_DEFS = DEFS;
